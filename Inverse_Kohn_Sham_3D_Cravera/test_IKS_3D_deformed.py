"""
test_IKS_3D_deformed.py
=======================
Self-contained test of the IKS reconstruction of densities generated by an
ANISOTROPIC (axially deformed) harmonic oscillator, delta = 0.6 and 0.3, on
the Gauss-Hermite Lagrange mesh. Thesis: Section 5.4 (Table 5.4, Fig. 5.13).

Figures produced
  1. deform_demo.pdf  — target density, reconstructed potential and reference
                        potential on the x-z plane, for each delta;
  2. deform_diff.pdf  — 2D maps of the DIFFERENCES reconstruction - target on
                        the x-z plane: d_rho = rho_IKS - rho_target and
                        dV = V_IKS - V_ref (thesis Fig. 5.13);
  3. deform_diff_slide.{pdf,png} — the same difference figure in a
                        "presentation" version: nodal values smoothly
                        interpolated on a fine grid (bicubic spline), optional
                        mesh nodes overlaid, no contour lines.

The reconstructed density is the one of the orbitals at the solution,
    rho_IKS = sum_k q_k phi_k^2,  phi_k = f_k sqrt(rho_target)
    =>  rho_IKS = rho_target sum_k q_k f_k^2,
so d_rho directly measures the residual violation of the density constraint.

Configuration and starting point
--------------------------------
By default (CONFIG = "fondamentale") the target is built from the GROUND
configuration of the deformed oscillator (aufbau on the deformed energies,
{(000),(001)} for delta > 0). Since the solver's default starting point uses
SPHERICAL orbitals, ``_install_deformed_start`` replaces it on the instance
with the deformed generating orbitals. CONFIG = "sferico" keeps the spherical
aufbau order ({(000),(100)}), which is an EXCITED configuration for delta > 0.

The run results are saved in deform_results.npz, so that the presentation
figure can be regenerated without running the solver again.

This file does NOT modify the solver: it reuses the infrastructure (consts3D,
eigenfunctions3D, orbitals3D, optimizer3D_lm, lagrange_mesh_3D) and
deformed.py for the anisotropic oscillator.

Usage
-----
  python test_IKS_3D_deformed.py               # full run + all figures
  python test_IKS_3D_deformed.py --plot-only   # figures only, from deform_results.npz
  add --nodes to overlay the mesh nodes on the presentation figure
"""
