_SAVE_KEYS_ARR = ("rho_target", "rho_iks", "V_iks", "V_ref")

def save_results(results, path):
    """Store the arrays and scalars needed by the presentation figure in a .npz file."""
    data = {}
    for i, r in enumerate(results):
        x, y, z = r['grid']
        data[f"r{i}_x"], data[f"r{i}_y"], data[f"r{i}_z"] = x, y, z
        data[f"r{i}_center"] = np.array(r['center'])
        data[f"r{i}_delta"] = np.array(r['delta'])
        for k in _SAVE_KEYS_ARR:
            data[f"r{i}_{k}"] = r[k]
        data[f"r{i}_rmse"] = np.array(r['pot_err']['rmse_pesato'])
        data[f"r{i}_L2"] = np.array(r['pot_pct']['L2_rel'])
        data[f"r{i}_rho_max_rel"] = np.array(r['rho_err']['max_rel'])
    data["n"] = np.array(len(results))
    np.savez_compressed(path, **data)
    print(f"  → Risultati salvati: {path}")


def load_results(path):
    """Inverse of save_results: list of result dicts (only the saved fields)."""
    d = np.load(path)
    out = []
    for i in range(int(d["n"])):
        r = {k: d[f"r{i}_{k}"] for k in _SAVE_KEYS_ARR}
        r['grid'] = (d[f"r{i}_x"], d[f"r{i}_y"], d[f"r{i}_z"])
        r['center'] = tuple(int(c) for c in d[f"r{i}_center"])
        r['delta'] = float(d[f"r{i}_delta"])
        r['rmse'] = float(d[f"r{i}_rmse"]); r['L2'] = float(d[f"r{i}_L2"])
        r['rho_max_rel'] = float(d[f"r{i}_rho_max_rel"])
        out.append(r)
    return out


