def _fill_nearest(vals, ok):
    """Fill the invalid nodes with the value of the nearest valid node (in grid
    indices). It only gives the spline a regular edge; the region shown is
    still rho >= frac*rho_max."""
    from scipy.ndimage import distance_transform_edt
    if ok.all():
        return vals
    idx = distance_transform_edt(~ok, return_distances=False, return_indices=True)
    return vals[tuple(idx)]


def _smooth_xz(r, arr3d, frac, n_fine=1201, frac_interp=0.3):
    """Nodal values on the x-z plane (y = y_c) interpolated on a fine grid.

    The Lagrange mesh is a tensor product (x_i, z_k): a bicubic interpolating
    spline on the rectangular grid of nodes is used (RectBivariateSpline,
    s = 0, exact on the nodes). Unlike interpolation on triangles, there are
    no facets or diagonal artefacts.
    - the target density is interpolated in log rho (~quadratic in the tails,
      smooth): the edge of the region shown, rho = frac*rho_max, is a smooth curve;
    - for the field, the nodes with rho >= frac_interp*frac*rho_max are used;
      the others are filled with the nearest valid value (noisy tails or NaN
      do not enter the spline).
    Returns (xf, data_fine, rho_fine/rho_max, nodes shown (x, z), L); the mask
    rho >= frac is applied (with a faded edge) by _slide_panel."""
    x, _, z = r['grid']; icy = r['center'][1]
    rho = r['rho_target']; rmax = rho.max()
    rho2 = rho[:, icy, :] / rmax                       # (x, z)
    val2 = np.asarray(arr3d[:, icy, :], dtype=float)
    X, Z = np.meshgrid(x, z, indexing="ij")
    show = (rho2 >= frac) & np.isfinite(val2)
    use = (rho2 >= frac_interp * frac) & np.isfinite(val2)
    logr = np.log(np.maximum(rho2, 1e-300))
    spl_r = RectBivariateSpline(x, z, logr, kx=3, ky=3, s=0)
    # window: extent of the region rho >= frac on the smooth contour (not just
    # on the nodes), so that the edge is not cut by the frame
    L0 = 1.4 * max(np.abs(X[show]).max(), np.abs(Z[show]).max())
    x0 = np.linspace(-L0, L0, 401)
    m0 = np.exp(spl_r(x0, x0).T) >= frac
    XX0, ZZ0 = np.meshgrid(x0, x0, indexing="xy")
    L = 1.08 * max(np.abs(XX0[m0]).max(), np.abs(ZZ0[m0]).max())
    xf = np.linspace(-L, L, n_fine)
    rho_f = np.exp(spl_r(xf, xf).T)                    # rows = z, columns = x
    filled = _fill_nearest(val2, use)
    data_f = RectBivariateSpline(x, z, filled, kx=3, ky=3, s=0)(xf, xf).T
    return xf, data_f, rho_f, (X[show], Z[show]), L    # data_f not masked


EDGE_FADE = 1.4   # width of the edge fade: from rho = 1% to 1.4% of rho_max
SLIDE_LEVELS = 21 # number of colour bands (odd: white band centred on 0)
CORE_FRAC = 0.05  # the colour scale is fixed where rho >= 5% rho_max: the tails
                  # (where V is poorly determined) saturate, flagged by the arrows


def _slide_lim(D, rho_f, frac, q=99.5):
    """Symmetric limit of the scale: q-th percentile of |D| in the core
    (rho >= CORE_FRAC*rho_max); 'extend' if it is exceeded in the region shown."""
    core = np.isfinite(D) & (rho_f >= CORE_FRAC)
    shown = np.isfinite(D) & (rho_f >= frac)
    v = np.percentile(np.abs(D[core]), q) if core.any() else 1.0
    v = v if v > 0 else 1.0
    return v, ("both" if np.abs(D[shown]).max() > 1.001 * v else "neither")


def _slide_panel(fig, ax, xf, data, rho_f, nodes, L, cmap, v, cbar_label,
                 extend, title, show_nodes=True, frac=None):
    """Field on the x-z plane, without contour lines. Towards the edge of the
    region rho >= frac*rho_max the colour fades gradually into white (see EDGE_FADE)."""
    frac = POT_FRAC if frac is None else frac
    ax.set_facecolor("white")
    # discrete colour levels (sharp bands, no lines): structures get defined
    # outlines instead of continuous shading that looks out of focus
    nl = SLIDE_LEVELS
    bounds = np.linspace(-v, v, nl + 1)
    cm = ListedColormap(plt.get_cmap(cmap)((np.arange(nl) + 0.5) / nl))
    cm.set_under(plt.get_cmap(cmap)(0.0)); cm.set_over(plt.get_cmap(cmap)(1.0))
    norm = BoundaryNorm(bounds, nl, extend="neither")
    q = np.clip(np.nan_to_num(data), -v, v * (1 - 1e-12))
    rgba = cm(norm(q))
    # alpha: gradual fade to white. It goes from 0 (rho = frac*rho_max) to 1
    # (rho = EDGE_FADE*frac*rho_max) with a smoothstep in log rho: no hard cut,
    # and the tails (where V is less determined) stay in the background
    t = np.log(np.maximum(rho_f, 1e-300) / frac) / np.log(EDGE_FADE)
    t = np.clip(t, 0.0, 1.0)
    rgba[..., 3] = t * t * (3.0 - 2.0 * t)
    # interpolation="none": in the PDF the image is embedded at its full
    # resolution (n_fine x n_fine), without resampling that would blur it
    ax.imshow(rgba, origin="lower", extent=(-L, L, -L, L), interpolation="none")
    if show_nodes:
        ax.plot(nodes[0], nodes[1], ".", ms=1.6, color="#1A1F24", alpha=0.35)
    ax.set_xlim(-L, L); ax.set_ylim(-L, L); ax.set_aspect("equal")
    ax.set_xlabel("x [fm]"); ax.set_ylabel("z [fm]")
    ax.set_title(title, pad=8)
    for sp in ax.spines.values():
        sp.set_linewidth(0.6)
    ax.tick_params(width=0.6, length=3)
    cax = ax.inset_axes([1.04, 0.0, 0.045, 1.0])
    sm = plt.cm.ScalarMappable(norm=norm, cmap=cm)
    cb = fig.colorbar(sm, cax=cax, extend=extend, spacing="uniform",
                      ticks=MaxNLocator(5, symmetric=True).tick_values(-v, v))
    cb.set_label(cbar_label)
    cb.outline.set_linewidth(0.5)
    cb.ax.tick_params(width=0.6, length=3)


def make_slide_figure(results, fig_base, show_nodes=True):
    """d_rho/rho_max and dV on the x-z plane, one row per delta, ready for a slide."""
    with plt.rc_context(SLIDE_STYLE):
        nrow = len(results)
        fig, axes = plt.subplots(nrow, 2, figsize=(8.6, 4.1 * nrow),
                                 constrained_layout=True, squeeze=False)
        fig.get_layout_engine().set(w_pad=0.12, wspace=0.05, h_pad=0.1)
        fig.suptitle("Differenze ricostruito − target sul piano x–z (Lagrange mesh)",
                     fontweight="bold")
        for i, r in enumerate(results):
            d = r['delta']
            # density
            drho = (r['rho_iks'] - r['rho_target']) / r['rho_target'].max()
            xf, D, rho_f, nodes, L = _smooth_xz(r, drho, POT_FRAC)
            v, ext = _slide_lim(D, rho_f, POT_FRAC); e = _scale_exp(v); s = 10.0**e
            lab = "Δρ / ρ$_{max}$" + (f"  [×10$^{{{e}}}$]" if e else "")
            _slide_panel(fig, axes[i][0], xf, D / s, rho_f, nodes, L, "RdBu_r", v / s,
                         lab, ext, f"δ = {d:+.2f}:  ρ$_{{IKS}}$ − ρ$_{{target}}$", show_nodes)
            # potential
            dV = r['V_iks'] - r['V_ref']
            xf, D, rho_f, nodes, L = _smooth_xz(r, dV, POT_FRAC)
            v, ext = _slide_lim(D, rho_f, POT_FRAC)
            _slide_panel(fig, axes[i][1], xf, D, rho_f, nodes, L, "RdBu_r", v,
                         "ΔV [MeV]", ext,
                         f"δ = {d:+.2f}:  V$_{{IKS}}$ − V$_{{rif}}$", show_nodes)
        for ext_ in ("pdf", "png"):
            fig.savefig(f"{fig_base}.{ext_}", dpi=300, bbox_inches="tight",
                        facecolor="white")
        plt.close(fig)
    print(f"  → Figura per le slide salvata: {fig_base}.pdf / .png")


