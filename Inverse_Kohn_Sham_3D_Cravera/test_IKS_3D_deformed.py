# ──────────────────────────────────────────────────────────────────────────────
# Target density (spherical if delta = 0, anisotropic otherwise)
# ──────────────────────────────────────────────────────────────────────────────
def _lengths(A, delta):
    """Oscillator lengths (bx, by, bz): spherical or deformed."""
    if abs(delta) > 1e-12:
        bp, bz = deformed_lengths(A, delta)
        return bp, bp, bz
    return b_x(A), b_y(A), b_z(A)


def _reference_potential(A, delta, X, Y, Z):
    """Reference harmonic potential (isotropic or anisotropic) on the meshgrid X, Y, Z."""
    if abs(delta) > 1e-12:
        nu_p, nu_z = deformed_nu(A, delta)
        return nu_p * (X**2 + Y**2) + nu_z * Z**2
    return nuclearNu_x(A) * X**2 + nuclearNu_y(A) * Y**2 + nuclearNu_z(A) * Z**2


def _occupied_qn(A, n_part, delta, config=None):
    """Quantum numbers (nx, ny, nz) of the occupied orbitals.

    getOrbitalSet orders the basis with the SPHERICAL aufbau: for A = 4 it
    occupies {(000),(100)}. In the deformed potential with delta > 0 (prolate,
    omega_z < omega_perp) that is an EXCITED configuration: the ground state is
    {(000),(001)}.
      config="fondamentale" -> aufbau on the deformed energies
          eps = hbar omega_perp (n_x + n_y + 1) + hbar omega_z (n_z + 1/2)
      config="sferico"      -> order of getOrbitalSet
    The occupations are those of getOrbitalSet.
    Returns (orbitals, list of (nx, ny, nz))."""
    config = config or CONFIG
    orbitals = list(getOrbitalSet(n_part, uncoupledHObasis()))
    if config == "sferico" or abs(delta) <= 1e-12:
        return orbitals, [(o.nx, o.ny, o.nz) for o in orbitals]
    wp, wz = deformed_frequencies(A, delta)
    nmax = 6
    cand = [(nx, ny, nz) for nx in range(nmax) for ny in range(nmax)
            for nz in range(nmax) if nx + ny + nz < nmax]
    # at equal energy (delta < 0: (100)/(010) degenerate) prefer x, then y
    cand.sort(key=lambda q: (round(wp * (q[0] + q[1] + 1) + wz * (q[2] + 0.5), 12),
                             -q[0], -q[1]))
    return orbitals, cand[:len(orbitals)]


def _orbitals_density(eval_wf, A, n_part, delta, norm_fn):
    """Normalised orbitals and density for a given wave-function evaluator.

    eval_wf(qn, bx, by, bz) with qn = (nx, ny, nz) returns the orbital on the
    grid; norm_fn(p) returns its squared norm with the grid quadrature.
    Returns (rho, phi_list, orbitals)."""
    bx, by, bz = _lengths(A, delta)
    orbitals, qns = _occupied_qn(A, n_part, delta)
    phi = []
    for q in qns:
        p = eval_wf(q, bx, by, bz)
        p = p / np.sqrt(norm_fn(p))
        phi.append(p)
    rho = sum(orbitals[k].occupation * phi[k]**2 for k in range(len(orbitals)))
    return rho, phi, orbitals


def _install_deformed_start(prob, delta, phi_norm):
    """Non-invasive override of the starting point.

    The solver's getStartingPoint() builds SPHERICAL orbitals, inconsistent
    with a deformed density. Here it is replaced ON THE INSTANCE by
    f = phi_deformed / sqrt(rho_target) (dead nodes at the plateau value).
    Since solve() always calls getStartingPoint(), this is the way to change
    the starting point without touching the solver."""
    if abs(delta) <= 1e-12:
        return
    rho_safe = np.maximum(prob.tab_rho, 1e-14 * prob.tab_rho.max())
    dead = prob.tab_rho < 1e-10 * prob.tab_rho.max()
    occ_tot = sum(o.occupation for o in prob.orbital_set)
    plateau = getattr(prob, "_plateau_value", None) or (1.0 / np.sqrt(occ_tot))
    st = np.zeros((prob.n_orbitals, prob.n_points_x, prob.n_points_y, prob.n_points_z))
    for j, p in enumerate(phi_norm):
        f = p / np.sqrt(rho_safe)
        f[dead] = plateau
        st[j] = f
    flat = st.ravel()
    prob.getStartingPoint = lambda: flat


# ──────────────────────────────────────────────────────────────────────────────
# Analytic kinetic energy (possibly anisotropic oscillator)
# ──────────────────────────────────────────────────────────────────────────────
def _analytic_Ekin(A, n_part, delta=0.0):
    """E = hbar omega_perp (n_x+n_y+1) + hbar omega_z (n_z+1/2) per orbital; T = E/2 (virial)."""
    orbitals, qns = _occupied_qn(A, n_part, delta)
    if abs(delta) > 1e-12:
        wp, wz = deformed_frequencies(A, delta)
        hwp, hwz = hbc * wp, hbc * wz
        E_tot = sum(o.occupation * (hwp * (q[0] + q[1] + 1) + hwz * (q[2] + 0.5))
                    for o, q in zip(orbitals, qns))
    else:
        hw = hbc * nuclear_omega_x(A)
        E_tot = sum(o.occupation * hw * (o.nx + o.ny + o.nz + 1.5) for o in orbitals)
    return 0.5 * E_tot


def _decompose_gh(mesh, rho, f_list, orbitals, beta):
    """T_alpha (expanded form with grad log sqrt(rho)) and T_beta, masked to the physical region."""
    mask = rho >= 1e-10 * rho.max()
    s = np.sqrt(np.maximum(rho, 1e-14 * rho.max()))
    glog = mesh.grad(np.log(s))
    nglog = np.sum(glog**2, axis=-1)
    T_a = T_b = 0.0
    for k, o in enumerate(orbitals):
        f = f_list[k]
        gf = mesh.grad(f)
        gm2 = np.sum(gf**2, axis=-1)
        dot = np.sum(glog * gf, axis=-1)
        T_a += o.occupation * mesh.integrate(ALPHA * rho * (gm2 + f**2*nglog + 2*f*dot) * mask)
        T_b += o.occupation * mesh.integrate(beta * gm2 * mask)
    return T_a, T_b


# ──────────────────────────────────────────────────────────────────────────────
# Run IKS — Lagrange mesh (Gauss–Hermite)
# ──────────────────────────────────────────────────────────────────────────────
def run_gh(A, n_part, N, beta, delta=0.0, dual_inf_tol=DUAL_INF_TOL):
    """Full IKS run on the (isotropic, s = 1) Lagrange mesh for deformation delta.

    Returns a dict with T_alpha, reconstructed/reference potentials and
    densities, error metrics (potential and density), timing and grid data.
    """
    mesh = LagrangeMesh3D(N, N, N, b_x(A), b_y(A), b_z(A))
    x, y, z = mesh.x, mesh.y, mesh.z

    rho_target, phi_norm, orbitals = _orbitals_density(
        lambda q, bx, by, bz: HO3D(q[0], q[1], q[2], bx, by, bz, mesh.dV)(x, y, z),
        A, n_part, delta, norm_fn=lambda p: mesh.integrate(p**2))
    n_orb = len(orbitals)

    prob = iKS_problem(
        Z=A, N=0, lb=[-2, -2, -2], ub=[2, 2, 2],
        data=[x, y, z, rho_target],
        basis=uncoupledHObasis(), reg_parameter=beta,
        output_folder="test_deformed_gh",
        exact_hess=True, max_iter=500,
        rel_tol=1e-4, constr_viol=1e-4, dual_inf_tol=dual_inf_tol,
        use_lagrange_mesh=True, Nx=N, Ny=N, Nz=N,
    )
    prob.add_option(b"mu_init", 0.01)
    _install_deformed_start(prob, delta, phi_norm)

    t0 = time.time()
    results, info = prob.solve()
    elapsed = time.time() - t0

    f_sol = results['x'].reshape(n_orb, mesh.Nx, mesh.Ny, mesh.Nz)
    f_list = [f_sol[k] for k in range(n_orb)]
    T_a, _ = _decompose_gh(mesh, rho_target, f_list, orbitals, beta)

    # reconstructed density: rho_IKS = rho_target sum_k q_k f_k^2 (physical nodes)
    mask = rho_target >= 1e-10 * rho_target.max()
    sum_qf2 = sum(o.occupation * f_list[k]**2 for k, o in enumerate(orbitals))
    rho_iks = np.where(mask, rho_target * sum_qf2, np.nan)

    # potential: V = lambda/(rho w) on the live nodes, gauge V = 0 at the density maximum
    lam_full = np.full(mesh.n_points, np.nan)
    lam_full[prob.live_nodes] = results['lagrange'][:prob.n_live]
    lam = lam_full.reshape(mesh.Nx, mesh.Ny, mesh.Nz)
    with np.errstate(divide='ignore', invalid='ignore'):
        V_iks = np.where(mask, lam / (rho_target * mesh.w3D), np.nan)
    ic = np.unravel_index(np.nanargmax(rho_target), rho_target.shape)
    V_iks -= V_iks[ic]

    X, Y, Z = np.meshgrid(x, y, z, indexing='ij')
    V_ref = _reference_potential(A, delta, X, Y, Z); V_ref -= V_ref[ic]
    pe = potential_error(V_iks, V_ref, rho_target, x, frac=1e-2)
    pot_pct = _potential_percent_error(V_iks, V_ref, rho_target, mesh.w3D, frac=1e-2)

    # integral error on the density
    drho = np.where(mask, rho_iks - rho_target, 0.0)
    rho_err = dict(
        max_rel=np.nanmax(np.abs(drho)) / rho_target.max(),
        L1_rel=mesh.integrate(np.abs(drho)) / mesh.integrate(rho_target),
    )

    return dict(T_alpha=T_a, V_iks=V_iks, V_ref=V_ref,
                rho_target=rho_target, rho_iks=rho_iks,
                pot_err=pe, pot_pct=pot_pct, rho_err=rho_err, elapsed=elapsed,
                center=ic, grid=(x, y, z), delta=delta)


def _potential_percent_error(V_iks, V_ref, rho, w3D, frac=1e-2):
    """Percentage errors on the reconstructed potential, in the physical region
    rho >= frac * rho_max (same threshold as potential_error).

    The potential is defined up to a constant (here V = 0 at the centre), so a
    pointwise relative error dV/V_ref diverges near the centre and is not
    meaningful. Two global measures are used instead:
      * density-weighted relative L2:
            eps_L2 = 100 * sqrt( sum rho w (dV)^2 / sum rho w V_ref^2 )
      * errors relative to the spread of the potential in the physical region,
            dV_span = max V_ref - min V_ref:
            eps_RMSE = 100 * RMSE_rho / dV_span,   eps_max = 100 * max|dV| / dV_span
    """
    valid = (rho >= frac * rho.max()) & np.isfinite(V_iks)
    dV = (V_iks - V_ref)[valid]
    Vr = V_ref[valid]
    wt = (rho * w3D)[valid]
    span = Vr.max() - Vr.min()
    rmse_w = np.sqrt(np.sum(wt * dV**2) / np.sum(wt))
    return dict(
        L2_rel=100.0 * np.sqrt(np.sum(wt * dV**2) / np.sum(wt * Vr**2)),
        rmse_span=100.0 * rmse_w / span,
        max_span=100.0 * np.max(np.abs(dV)) / span,
        span=span,
    )


